// ILIKE/LIKE интерпретирует %, _ и \ как спецсимволы паттерна даже в параметризованном запросе —
// параметризация защищает от SQL-инъекции, но не от того, что пользовательский ввод, содержащий
// эти символы, ведёт себя как wildcard вместо литерала. Postgres по умолчанию использует `\` как
// escape-символ для LIKE/ILIKE, поэтому экранируем именно им.
export function escapeLikePattern(value: string): string {
  return value.replace(/[\\%_]/g, (char) => `\\${char}`);
}
