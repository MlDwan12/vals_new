// Исход записи журнала — семантика вместо сырого HTTP-кода: в фильтре человеку нужно «покажи
// отказы», а не «покажи 401 и 403». Сам код остаётся в записи и виден в карточке.
export enum AuditOutcome {
  SUCCESS = 'success',
  DENIED = 'denied',
  ERROR = 'error',
}

// 401 и 403 — «не пустили»: неудачный вход, истёкший доступ, нехватка права. Всё остальное от 400
// и выше — сбой запроса (валидация, не найдено, падение), и смешивать их нельзя: отказ в доступе
// читают как сигнал безопасности, а ошибку — как поломку.
export const DENIED_STATUS_CODES = [401, 403];
