// Оставляет достаточно для ручного поиска контакта человеком (последние 4 символа телефона/email),
// не полное значение — контакт целиком не должен оказаться в логах ни при каких обстоятельствах
// (R4, round-2 review).
export function maskTail(value: string): string {
  return value.length > 4 ? `…${value.slice(-4)}` : '****';
}
